function expand(): WealthHealthHistoryRow[] {
  return series.flatMap(({ code, country, region, gdp, life, pop }) =>
    gdp.map((_, index) => ({
      country,
      code,
      region,
      year: FIRST_YEAR + index,
      gdp: gdp[index],
      life: life[index],
      pop: pop[index],
    })),
  );
}

