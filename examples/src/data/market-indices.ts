/**
 * Six major equity indices as 40-point intraday-style series, for the
 * sparkline card grid on the Dashboards page.
 *
 * The values are synthetic biased random walks (a seeded PRNG produced them,
 * then they were frozen to static arrays so the module carries no runtime
 * randomness). Levels start near each index's early-2026 range but the paths
 * are illustrative, not historical closes — hence the 'Illustrative data'
 * marker and no source URL.
 */

type Point = { t: number; value: number };

function toSeries(values: readonly number[]): Point[] {
  return values.map((value, t) => ({ t, value }));
}

