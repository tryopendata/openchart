/** A resolved annotation with computed pixel positions. */
export interface ResolvedAnnotation {
  /** Original annotation type. */
  type: 'text' | 'range' | 'refline';
  /** Stable identifier from the spec annotation, for selection/edit callbacks. */
  id?: string;
  /**
   * Index of the originating annotation in `spec.annotations`.
   *
   * The resolved array is a *filtered* view of the spec array -- an annotation
   * whose position falls outside the scale domain resolves to nothing and is
   * dropped -- so a resolved array index is NOT a spec index. Anything that has
   * to reach back to the authored annotation (thinning's priority/responsive
   * lookup, faceted footnote numbering) must key on this.
   */
  specIndex?: number;
  /** Label text (if any). */
  label?: ResolvedLabel;
  /** For range: the highlighted rectangle in pixel coordinates. */
  rect?: Rect;
  /** For refline: the line start and end in pixel coordinates. */
  line?: { start: Point; end: Point };
  /** Fill color. */
  fill?: string;
  /** Stroke color. */
  stroke?: string;
  /** Opacity. */
  opacity?: number;
  /** Line dash pattern for reflines. */
  strokeDasharray?: string;
  /** Stroke width. */
  strokeWidth?: number;
  /** Z-index for render ordering. Higher values render on top. */
  zIndex?: number;
  /**
   * For text annotations: the endpoint marker drawn at the data point.
   * Coordinates sit on the data point itself (plus any `connectorOffset.to`),
   * not on the pulled-back `label.connector.to`.
   */
  dot?: {
    x: number;
    y: number;
    radius: number;
    fill: string;
    stroke: string;
    strokeWidth: number;
  };
  /**
   * For text annotations: optional muted subtitle rendered below the primary
   * label. Positioned `lineHeight * primaryLineCount + gap` below `label.y`.
   */
  subtitle?: {
    text: string;
    x: number;
    y: number;
    style: TextStyle;
  };
  /** Full placed extent: label bounds unioned with subtitle bounds. Collision and placement source of truth. */
  bounds?: Rect;
  /**
   * When set, this annotation was demoted to a footnote marker by auto-thinning.
   * The label is replaced by a numbered dot at the data point; the original text
   * appears in the chrome footnote band. 1-indexed.
   */
  footnoteIndex?: number;
}

/** A footnote entry generated by annotation auto-thinning. */
export interface AnnotationFootnote {
  /** 1-indexed footnote number matching the dot marker on the chart. */
  index: number;
  /** The original annotation text that was demoted. */
  text: string;
}

