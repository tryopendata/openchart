/**
 * Options passed to the engine's compile functions.
 *
 * Width and height define the total available space. The engine subtracts
 * chrome, axes, and legend to compute the chart drawing area.
 */
export interface CompileOptions {
  /** Total available width in pixels. */
  width: number;
  /** Total available height in pixels. */
  height: number;
  /**
   * How chrome height interacts with the height budget. Mirrors the spec-level
   * `chromeLayout`; the engine reads whichever is set (spec wins).
   *
   * - `'subtract'` (default): `height` is the fixed total; chrome shrinks the plot.
   * - `'grow'`: `height` is the plot budget; the SVG grows by the chrome height.
   */
  chromeLayout?: 'subtract' | 'grow';
  /** Theme overrides. */
  theme?: import('./spec').ThemeConfig;
  /**
   * Resolved dark mode boolean.
   *
   * Note: this is a boolean, not the DarkMode union ("auto" | "force" | "off").
   * Adapters resolve "auto" by checking window.matchMedia('(prefers-color-scheme: dark)')
   * before calling compile. The engine always receives a resolved boolean.
   */
  darkMode?: boolean;
  /**
   * Rendering backend for point marks, mirroring vega-embed's `renderer`
   * embed option: backend choice is host policy, not part of the spec.
   * High-cardinality scatter plots draw thousands of SVG circles, which is
   * what makes their entrance and update transitions stutter; a canvas layer
   * draws the same dots in a handful of batched paint calls.
   *
   * - `'auto'` (default): canvas above 1,000 compiled point marks, SVG below.
   * - `'svg'`: always SVG, whatever the point count.
   * - `'canvas'`: always canvas, whatever the point count.
   *
   * Canvas mode trades per-mark keyboard focus and edit-mode point selection
   * (the screen-reader data table still carries every row), and draws the
   * trendline above the dots even when `trendline.layer` is `'below'`.
   * Tooltips, hover, and click callbacks work the same in both modes.
   *
   * Ignored with a console warning for non-point marks, and for faceted,
   * layered, and sparkline charts.
   */
  renderer?: 'auto' | 'svg' | 'canvas';
  /** Whether to show the OpenData watermark. Defaults to true. */
  watermark?: boolean;
  /**
   * Enable development-time diagnostics (WCAG contrast warnings via
   * `console.warn`). The engine is isomorphic, so it never sniffs
   * `process.env`; the host decides what "dev" means and passes this flag.
   * Warnings are advisory only and never throw. Defaults to false.
   */
  dev?: boolean;
  /**
   * Sink for advisory spec warnings (deprecations, did-you-mean suggestions,
   * unknown scheme names, overplotting/beeswarm budget notes, etc.). The engine
   * is isomorphic and side-effect-free by default: rather than writing to the
   * global `console`, it routes every advisory warning through this callback so
   * a host can collect, reroute, or silence them (e.g. suppress under SSR, fail
   * a test on any warning, surface them in a dev overlay). When omitted, the
   * engine defaults to `console.warn`. Never called with fatal errors, which are
   * thrown instead.
   */
  onWarn?: (message: string) => void;
  /**
   * Real text measurement function provided by the adapter.
   * Uses a hidden canvas or DOM element for accurate text dimensions.
   * If not provided, the engine falls back to heuristic estimation.
   */
  measureText?: MeasureTextFn;
  /** Extra pixels to reserve on the right margin for a secondary y-axis. Set by compileLayer when resolve.scale.y is 'independent'. */
  rightAxisReserve?: number;
  /**
   * Extra pixels to reserve below the plot for the auto-thinning footnote list.
   * Chicken-and-egg: thinning needs the chart area to decide what to demote, but
   * the footnotes it produces need space carved out of that same area. compileChart
   * resolves it by compiling once to learn the footnote count, then recompiling with
   * this set. Callers should not set it; it is internal to that second pass.
   */
  footnoteReserve?: number;
  /** Recursion depth of the footnote-reserve convergence pass. Internal to compileChart. */
  footnotePass?: number;
  /** Set after facet height growth to prevent unbounded recursion. Internal to compileFaceted. */
  facetHeightGrown?: boolean;
  /**
   * Use this chart drawing area instead of computing one from chrome, axes,
   * and legend reservations. Set by compileLayer when compiling leaf layers so
   * their marks land in the primary layout's coordinate space; leaf specs lack
   * the layer-level chrome/legend/theme and would otherwise compute a
   * different area than the one the axes are rendered in.
   */
  frozenChartArea?: Rect;
  /**
   * Marks this compile as one leaf (or the primary spec) of a multi-leaf layer.
   * Set by compileLayer; callers should not set it. Only consumer today is the
   * canvas mark-layer resolution, which refuses canvas mode for layered charts
   * because the layer layout concatenates marks from several compiles.
   */
  layered?: boolean;
}

