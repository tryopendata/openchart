/** Accessibility attributes for a mark. */
export interface MarkAria {
  /** ARIA label for the mark. Optional when `decorative: true` — decorative
   *  marks render with `aria-hidden="true"` and don't need a label. */
  label?: string;
  /** Optional longer description. */
  description?: string;
  /** ARIA role override. */
  role?: string;
  /** When true, the mark is purely decorative (e.g. a sparkline endpoint dot
   *  that duplicates an existing data point). Renderers translate this into
   *  `aria-hidden="true"` and skip the mark from the screen-reader data table. */
  decorative?: boolean;
}

/**
 * Line mark: a series of connected points.
 * Used by line charts and area chart boundaries.
 */
export interface LineMark {
  type: 'line';
  /** Stable identity key for data-update transitions. */
  key?: string;
  /** Per-point identity keys parallel to `points`, for data-update transitions. */
  pointKeys?: string[];
  /** Ordered array of points defining the line path. */
  points: Point[];
  /** Pre-computed SVG path string (D3 monotone curve). When present, renderers
   *  should use this instead of reconstructing straight M/L segments from points. */
  path?: string;
  /** Curve interpolation method used to build the path. Stored so the transition
   *  driver can reconstruct paths from interpolated point positions. */
  interpolate?: string;
  /** Stroke color. */
  stroke: string;
  /** Stroke width in pixels. */
  strokeWidth: number;
  /** Line dash pattern (empty for solid). */
  strokeDasharray?: string;
  /** Overall opacity for the line (0-1). */
  opacity?: number;
  /** Series identifier (for multi-series charts). */
  seriesKey?: string;
  /** Original data rows for this series. */
  data: Record<string, unknown>[];
  /**
   * Pixel-coordinate data points for spatial tooltip lookup (voronoi overlay).
   * Each entry pairs a pixel position with its original data row.
   */
  dataPoints?: Array<{
    x: number;
    y: number;
    datum: Record<string, unknown>;
    tooltip?: TooltipContent;
  }>;
  /** Resolved label after collision detection. */
  label?: ResolvedLabel;
  /** Accessibility attributes. */
  aria: MarkAria;
  /** Index for stagger animation ordering. */
  animationIndex?: number;
  /** Which y-scale produced this mark ('y' = left, 'y2' = right). */
  yScale?: 'y' | 'y2';
}

