/** A single axis tick with computed position and formatted label. */
export interface AxisTick {
  /** The raw data value at this tick. */
  value: unknown;
  /** Pixel position along the axis. */
  position: number;
  /** Formatted label string for display. */
  label: string;
  /**
   * The untruncated label, set only when `label` was shortened with an ellipsis
   * to fit the rotated-tick reservation. Renderers should surface this as the
   * tick's accessible/tooltip text so the full category name is never lost.
   */
  fullLabel?: string;
  /** Secondary label text from axis.labelField. */
  subtitle?: string;
  /**
   * Pixel position the LABEL is drawn at, set only when it differs from
   * `position` because the label was nudged inward to stay inside the
   * container. Point/band x-scales run flush to the plot edges, so a label
   * centered on the outermost tick can spill past the SVG. Gridlines, marks
   * and transitions still key off `position`; only the text moves.
   */
  labelPosition?: number;
}

/** A single gridline with computed positions. */
export interface Gridline {
  /** Pixel position along the axis. */
  position: number;
  /** Whether this is a major or minor gridline. */
  major: boolean;
}

/** Resolved axis layout with computed tick positions and labels. */
export interface AxisLayout {
  /** Axis ticks with positions and labels. */
  ticks: AxisTick[];
  /** Gridlines at tick positions. */
  gridlines: Gridline[];
  /** Axis label text (e.g. "GDP Growth (%)"). */
  label?: string;
  /** Label style. */
  labelStyle?: TextStyle;
  /** Tick label style. */
  tickLabelStyle: TextStyle;
  /** Rotation angle in degrees for tick labels. */
  tickAngle?: number;
  /** Axis line start position. */
  start: Point;
  /** Axis line end position. */
  end: Point;
  /** Axis orientation (which side it appears on). */
  orient?: 'top' | 'bottom' | 'left' | 'right';
  /** Whether to show the axis domain line. Defaults to true. */
  domainLine?: boolean;
  /** Whether to show tick marks. Defaults to true. */
  tickMarks?: boolean;
  /** Axis position offset in pixels. */
  offset?: number;
  /** Padding between axis title and axis in pixels. */
  titlePadding?: number;
  /** Padding between tick labels and axis in pixels. */
  labelPadding?: number;
  /** How overlapping labels should be handled. */
  labelOverlap?: boolean | 'parity' | 'greedy';
  /** Whether to flush labels to the axis edges. */
  labelFlush?: boolean;
  /**
   * Where tick labels render relative to the chart area.
   * `'inline'` puts y-axis labels above their gridlines at chart-area x and
   * suppresses the axis line and tick marks. `'gutter'` (default) keeps the
   * classic outside-the-area placement.
   */
  tickPosition?: 'inline' | 'gutter';
  /** Extent in px beyond the chart-area edge occupied by tick labels + title. Engine-resolved from the final (post-thinning) tick set. */
  extent?: number;
  /** Absolute anchor for the axis title. Replaces renderer-side offset math. */
  titlePosition?: { x: number; y: number; angle?: number };
}

