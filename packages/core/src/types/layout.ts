/** Base legend layout fields shared by all legend types. */
export interface BaseLegendLayout {
  /** Where the legend is positioned relative to the chart area. */
  position: 'top' | 'right' | 'bottom' | 'bottom-right' | 'inline';
  /** Bounding box for the legend (pixel coordinates). */
  bounds: Rect;
  /** Entry label style. */
  labelStyle: TextStyle;
}

/** Engine-resolved absolute position for a single legend entry. */
export interface LegendEntryPosition {
  x: number;
  y: number;
  labelX: number;
  labelY: number;
  width: number;
  row: number;
}

/** Categorical legend with discrete swatch entries. */
export interface CategoricalLegendLayout extends BaseLegendLayout {
  /** Discriminant for legend type. Omitted means categorical (backwards compat). */
  type?: 'categorical';
  /** Legend entries. */
  entries: LegendEntry[];
  /** Swatch size in pixels. */
  swatchSize: number;
  /** Gap between swatch and label. */
  swatchGap: number;
  /** Gap between entries. */
  entryGap: number;
  /** Fill color for the rounded chip background behind the colored bar. */
  swatchChipFill: string;
  /** Engine-resolved absolute positions, parallel to `entries`. */
  entryPositions?: LegendEntryPosition[];
  /** Row advance used to build entryPositions (single source of truth). */
  rowHeight?: number;
}

/** A color stop in a gradient legend. */
export interface GradientColorStop {
  /** Position along the gradient (0 to 1). */
  offset: number;
  /** CSS color value. */
  color: string;
  /** Optional stop-opacity (0 to 1). */
  opacity?: number;
}

/** Gradient legend for continuous color scales. */
export interface GradientLegendLayout extends BaseLegendLayout {
  /** Discriminant for legend type. */
  type: 'gradient';
  /** Color stops for the gradient bar. */
  colorStops: GradientColorStop[];
  /** Formatted minimum value label. */
  minLabel: string;
  /** Formatted maximum value label. */
  maxLabel: string;
}

/** A positioned value label on a continuous/binned color legend. */
export interface ContinuousLegendTick {
  /** The data value this label marks. */
  value: number;
  /** Formatted label text (channel format applied). */
  label: string;
  /** Label x position (pixel coordinates). */
  x: number;
  /** Horizontal text anchor for the label. */
  anchor: 'start' | 'middle' | 'end';
}

/** A discrete class swatch in a binned continuous legend. */
export interface ContinuousLegendBin {
  /** Swatch x position (pixel coordinates). */
  x: number;
  /** Swatch width in pixels. */
  width: number;
  /** Fill color. */
  color: string;
}

/**
 * Continuous color legend for quantitative color scales on charts.
 *
 * Two rendering modes, resolved from the color channel's scale type:
 * - `gradient`: a single gradient-filled bar with min/max labels (plus a
 *   midpoint label at the neutral value for diverging ramps).
 * - `binned`: a contiguous swatch row (quantile/quantize/threshold scales)
 *   with boundary value labels between swatches at the class breaks.
 */
export interface ContinuousLegendLayout extends BaseLegendLayout {
  /** Discriminant for legend type. */
  type: 'continuous';
  /** Rendering mode: gradient bar or binned swatch row. */
  mode: 'gradient' | 'binned';
  /** The color bar rectangle (pixel coordinates). */
  bar: Rect;
  /** Gradient color stops (empty in binned mode). */
  colorStops: GradientColorStop[];
  /** Class swatches, left to right (empty in gradient mode). */
  bins: ContinuousLegendBin[];
  /** Value labels rendered below the bar. */
  ticks: ContinuousLegendTick[];
  /** Text baseline y for the value labels (pixel coordinates). */
  labelY: number;
}

/** Resolved legend layout: categorical (swatches), gradient (tilemap bar), or continuous (chart color bar). */
export type LegendLayout = CategoricalLegendLayout | GradientLegendLayout | ContinuousLegendLayout;

