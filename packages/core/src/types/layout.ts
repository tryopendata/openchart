/**
 * A resolved label: text with a computed position after collision detection.
 * The collision engine determines whether labels are visible or demoted to tooltip-only.
 */
export interface ResolvedLabel {
  /** Label text content. */
  text: string;
  /** Computed x position. */
  x: number;
  /** Computed y position (baseline). */
  y: number;
  /** Text style. */
  style: TextStyle;
  /** Whether this label is visible or was demoted to tooltip-only by collision detection. */
  visible: boolean;
  /** Maximum available width for the label text. When set, the renderer should wrap or truncate. */
  maxWidth?: number;
  /** If not at the anchor point, draw a connector line from label to anchor. */
  connector?: {
    /** Connector start (at the label). */
    from: Point;
    /** Connector end (pulled back from the data point so the line doesn't touch it). */
    to: Point;
    /** Actual data point the connector is calling out. Renderer uses this for the endpoint marker. */
    endpoint?: Point;
    /** Author's from-end nudge, re-applied on every geometry rebuild (mirrors `endpoint` for `to`). */
    fromOffset?: { dx: number; dy: number };
    /** Connector line color. */
    stroke: string;
    /** Connector style: straight line, curved arrow, or vertical drop-line through the data point. */
    style: 'straight' | 'curve' | 'drop-line';
    /** Whether to draw an arrowhead at the data-point end. */
    arrow: boolean;
    /**
     * Which edge of the label block the connector leaves from. Renderers use it
     * to shape the curve's control point. Internal; not part of the spec.
     */
    exit?: 'horizontal' | 'vertical';
  };
  /** Background color behind the label text. */
  background?: string;
  /** Whether to show the paint-order stroke halo. Default true. */
  halo?: boolean;
  /** Engine-measured text-block bounds. Renderers should use this for background rects instead of re-estimating. */
  bounds?: Rect;
  /** Source index carried through from the LabelCandidate, if the caller set one. */
  index?: number;
}

